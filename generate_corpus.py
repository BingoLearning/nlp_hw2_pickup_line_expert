def build_corpus():
    conversations = []
    prefixes = ["", "朋友問我：", "請溫柔一點，", "想要簡短一點，"]
    for prefix in prefixes:
        for first_user, first_assistant, second_user, second_assistant in SCENARIOS:
            conversations.append({"messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prefix + first_user},
                {"role": "assistant", "content": first_assistant},
                {"role": "user", "content": second_user},
                {"role": "assistant", "content": second_assistant},
            ]})
    CORPUS_FILE.parent.mkdir(parents=True, exist_ok=True)
    with CORPUS_FILE.open("w", encoding="utf-8") as file:
        for row in conversations:
            file.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Created {len(conversations)} multi-turn conversations: {CORPUS_FILE}")
    return conversations


if __name__ == "__main__":
    build_corpus()

